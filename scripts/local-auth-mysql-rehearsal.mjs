import assert from "node:assert/strict";
import { spawn, spawnSync } from "node:child_process";
import { randomBytes } from "node:crypto";
import { mkdir, mkdtemp, readFile, writeFile } from "node:fs/promises";
import { createServer } from "node:net";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { setTimeout as delay } from "node:timers/promises";
import mysql from "mysql2/promise";
import { assertDisposableDatabase } from "./auth-migration-rehearsal.mjs";

// Always creates a new local MySQL instance. Never accepts DATABASE_URL, an
// existing datadir, a remote host, or a reusable database as input.
if (!process.argv.includes("--confirm-disposable")) throw new Error("confirm_disposable_required");
if (!process.env.AUTH_REHEARSAL_MYSQLD) throw new Error("AUTH_REHEARSAL_MYSQLD_required");
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
// MySQL on Windows cannot create ALTER-table scratch paths beyond MAX_PATH.
const scratch = resolve(tmpdir());
const runtime = await mkdtemp(join(scratch, "masari-auth-"));
assert(runtime.startsWith(scratch + "/") || runtime.startsWith(scratch + "\\"));
const data = join(runtime, "data");
const password = randomBytes(32).toString("hex");
const server = createServer();
await new Promise((ok, fail) => { server.once("error", fail); server.listen(0, "127.0.0.1", ok); });
const port = server.address().port;
await new Promise((ok) => server.close(ok));
const mysqld = process.env.AUTH_REHEARSAL_MYSQLD;
const init = spawnSync(mysqld, ["--no-defaults", "--initialize-insecure", `--datadir=${data}`], { windowsHide: true, encoding: "utf8" });
assert.equal(init.status, 0, "isolated_mysql_initialization_failed");
const initFile = join(runtime, "bootstrap.sql");
await writeFile(initFile, `ALTER USER 'root'@'localhost' IDENTIFIED BY '${password}';\n`, { mode: 0o600 });
const child = spawn(mysqld, ["--no-defaults", `--datadir=${data}`, `--port=${port}`, "--bind-address=127.0.0.1", "--mysqlx=OFF", `--init-file=${initFile}`, `--log-error=${join(runtime, "mysql.err")}`], { windowsHide: true, stdio: "ignore" });
let connection;
const checks = [];
const base = "origin/production-readiness";
const git = (args) => {
  const result = spawnSync("git", args, { cwd: root, windowsHide: true, encoding: "utf8" });
  assert.equal(result.status, 0, "rehearsal_git_read_failed"); return result.stdout.trimEnd();
};
const envFor = (database) => {
  const databaseUrl = new URL("mysql://127.0.0.1");
  databaseUrl.username = "root";
  databaseUrl.password = password;
  databaseUrl.port = String(port);
  databaseUrl.pathname = database;
  return { ...process.env, APP_ENV: "local", ENABLE_DEMO_FEATURES: "false", DATABASE_URL: databaseUrl.toString(), JWT_SECRET: randomBytes(32).toString("hex"), REFRESH_TOKEN_PEPPER: randomBytes(32).toString("hex"), AUTH_ACTION_TOKEN_PEPPER: randomBytes(32).toString("hex"), GOOGLE_PASSENGER_SIGNUP_MODE: "open", GOOGLE_MOBILE_SERVER_CLIENT_ID: "rehearsal-mobile-client", LOG_LEVEL: "silent" };
};
async function command(args, env, label) {
  const result = spawnSync(process.execPath, args, { cwd: root, env, windowsHide: true, encoding: "utf8", timeout: 180000, maxBuffer: 4 * 1024 * 1024 });
  // Child diagnostics may contain URLs or provider proofs: record only labels,
  // status, and an already-redacted runtime matrix generated by the child.
  if (result.status !== 0) {
    await writeFile(join(runtime, "failure-redacted.txt"), `${label}\n${(result.stdout + result.stderr).replaceAll(password, "[REDACTED]")}`);
    throw new Error(`${label}_failed (redacted diagnostics in runtime directory)`);
  }
  checks.push(label);
}
try {
  for (let attempt = 0; attempt < 100; attempt++) {
    try { connection = await mysql.createConnection({ host: "127.0.0.1", port, user: "root", password }); break; } catch { await delay(200); }
  }
  assert(connection, "isolated_mysql_start_failed");
  // Overwrite only this exact generated secret file once MySQL consumed it.
  await writeFile(initFile, "-- consumed bootstrap credential\n");
  const [[version]] = await connection.query("SELECT VERSION() AS version");
  const baseline = join(runtime, "baseline");
  const paths = git(["ls-tree", "-r", "--name-only", base, "apps/api/prisma"]).split(/\r?\n/).filter((p) => p.endsWith("schema.prisma") || p.includes("/migrations/"));
  for (const path of paths) {
    const target = join(baseline, path.slice("apps/api/prisma/".length));
    await mkdir(dirname(target), { recursive: true });
    await writeFile(target, git(["show", `${base}:${path}`]) + "\n");
  }
  const baselineConfig = join(runtime, "baseline.config.ts");
  await writeFile(baselineConfig, `export default { schema: ${JSON.stringify(join(baseline, "schema.prisma"))}, migrations: { path: ${JSON.stringify(join(baseline, "migrations"))} }, datasource: { url: process.env.DATABASE_URL } };\n`);
  const prismaCli = "node_modules/prisma/build/index.js";
  for (const scenario of ["upgrade", "fresh"]) {
    const database = `masari_auth_rehearsal_${scenario}_${Date.now()}`;
    assertDisposableDatabase(database);
    await connection.query(`CREATE DATABASE \`${database}\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci`);
    const env = envFor(database);
    if (scenario === "upgrade") {
      await command([prismaCli, "migrate", "deploy", "--config", baselineConfig], env, "production_readiness_baseline_deploy");
      await connection.query(`INSERT INTO \`${database}\`.users (id,name,phone,email,google_sub,password_hash,role) VALUES ('legacy-auth-rehearsal','TEST ONLY Legacy','+12025550123','legacy@example.invalid','legacy-google-rehearsal','unused-rehearsal-hash','passenger')`);
    }
    await command([prismaCli, "migrate", "deploy", "--config", "apps/api/prisma.config.ts"], env, `${scenario}_auth_migrations_deploy`);
    await command([prismaCli, "migrate", "deploy", "--config", "apps/api/prisma.config.ts"], env, `${scenario}_repeated_deploy`);
    await command([prismaCli, "migrate", "status", "--config", "apps/api/prisma.config.ts"], env, `${scenario}_migration_status_current`);
    if (scenario === "upgrade") {
      const [[row]] = await connection.query(`SELECT u.google_sub,e.provider_subject FROM \`${database}\`.users u JOIN \`${database}\`.external_identities e ON e.user_id=u.id WHERE u.id='legacy-auth-rehearsal'`);
      assert.equal(row.google_sub, "legacy-google-rehearsal"); assert.equal(row.provider_subject, row.google_sub); checks.push("legacy_google_sub_preserved_and_backfilled");
    }
    await command(["--import", "tsx", "apps/api/src/scripts/authRuntimeRehearsal.ts"], env, `${scenario}_auth_runtime_matrix`);
  }
  const evidence = { runtime: version.version, base: git(["rev-parse", base]), head: git(["rev-parse", "HEAD"]), checks, realDatabase: true, externalGoogleAndDelivery: "test_boundary_only", completedAt: new Date().toISOString() };
  await writeFile(join(runtime, "evidence.json"), JSON.stringify(evidence, null, 2));
  console.log(JSON.stringify({ ...evidence, evidenceDirectory: runtime }, null, 2));
} finally {
  if (connection) { await connection.query("SHUTDOWN").catch(() => {}); await connection.end().catch(() => {}); }
  if (child.exitCode === null) child.kill();
}
